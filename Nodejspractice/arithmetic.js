function addition(num1, num2){
    return num1+num2;
}

function division(num1, num2){
    return num1/num2;
}

function substraction(num1, num2){
    return num1-num2;
}

function multiplication(num1, num2){
    return num1*num2;
}

module.exports = { addition, substraction, multiplication, division};